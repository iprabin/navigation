#!/usr/bin/env node
'use strict';
/**
 * Derives `RouteParams` from the route tree so no one writes it by hand.
 *
 *   app-navigation-codegen [--project tsconfig.json] [--out <file>] [--watch|--check]
 *
 * Writes into the installed package (node_modules/app-navigation/generated),
 * which `src/index.ts` pulls in with a triple-slash reference — so an app gets
 * typed routes without touching its tsconfig, and the file stays out of its
 * source tree.
 *
 * Every `<Route>` / `<Modal>` name becomes a key; its params come from the
 * screen component's own props, which is the single source of truth. `<Tab>`,
 * `<Stack>` and `<Tab.Top>` names are keys too (they take no params) so goTo() can reach
 * a tab or a top-tab bar.
 *
 * JSX types are erased by TypeScript — `typeof routes` knows nothing about the
 * tree — so this reads the components through the type checker instead.
 */
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

const TAGS = new Set(['Route', 'Modal', 'Tab', 'Stack', 'Tab.Top']);
const MERGES = new Set(['Tab', 'Stack', 'Tab.Top']); // declared by several files on purpose; take no params

const STUB = `// Generated by app-navigation-codegen. Do not edit — rerun the script.
declare module 'app-navigation' {
  interface RouteParams {}
}

export {};
`;

function arg(flag, fallback) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? fallback : process.argv[i + 1];
}

const cwd = process.cwd();
const configPath = path.resolve(cwd, arg('--project', 'tsconfig.json'));
const check = process.argv.includes('--check');
const watch = process.argv.includes('--watch');

/** Where the library is actually installed — a symlink in a workspace. */
function defaultOut() {
  try {
    const pkg = require.resolve('app-navigation/package.json', { paths: [cwd] });
    return path.join(path.dirname(pkg), 'generated', 'routes.d.ts');
  } catch {
    console.error(`[navigation] cannot resolve app-navigation from ${cwd}. Pass --out.`);
    process.exit(1);
  }
}

const outPath = path.resolve(cwd, arg('--out', defaultOut()));
const shown = path.relative(cwd, outPath);

// `prepack` runs this so an app's routes are never published inside the library.
if (process.argv.includes('--reset')) {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, STUB);
  console.log(`${shown}: reset to an empty RouteParams`);
  process.exit(0);
}

if (!fs.existsSync(configPath)) {
  console.error(`[navigation] no tsconfig at ${configPath}`);
  process.exit(1);
}

/** Reads every route declaration in the program and returns the .d.ts text. */
function collect(program) {
  const checker = program.getTypeChecker();
  const printer = ts.createPrinter();
  const blank = ts.createSourceFile('_.ts', '', ts.ScriptTarget.Latest);
  const routes = new Map();
  const warnings = [];

  /** Is this `<Route>` ours, or some unrelated component that shares the name? */
  const fromLibrary = (tag) => {
    const root = ts.isPropertyAccessExpression(tag) ? tag.expression : tag;
    let symbol = checker.getSymbolAtLocation(root);
    if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol);
    return (symbol?.declarations ?? []).some((d) =>
      d.getSourceFile().fileName.includes('app-navigation')
    );
  };

  const attribute = (el, name) =>
    el.attributes.properties.find((p) => ts.isJsxAttribute(p) && p.name.getText() === name)
      ?.initializer;

  /** The screen's own params: the `route.params` of the props it accepts. */
  const paramsTypeOf = (type, location) => {
    const signature =
      checker.getSignaturesOfType(type, ts.SignatureKind.Call)[0] ??
      checker.getSignaturesOfType(type, ts.SignatureKind.Construct)[0];
    const first = signature?.getParameters()[0];
    if (!first) return undefined;
    const route = checker.getTypeOfSymbolAtLocation(first, location).getProperty('route');
    if (!route) return undefined;
    const params = checker.getTypeOfSymbolAtLocation(route, location).getProperty('params');
    return params && checker.getTypeOfSymbolAtLocation(params, location);
  };

  /** The screen's own params: the `route.params` of the props it accepts. */
  const paramsType = (expr) => paramsTypeOf(checker.getTypeAtLocation(expr), expr);

  /** The `default` component carried by a ScreenLoader's promised result. */
  const loaderParamsType = (expr) => {
    const signature = checker.getSignaturesOfType(checker.getTypeAtLocation(expr), ts.SignatureKind.Call)[0];
    const promise = signature && checker.getReturnTypeOfSignature(signature);
    const promised = promise && checker.getPromisedTypeOfPromise(promise);
    const component = promised && promised.getProperty('default');
    const type = component && checker.getTypeOfSymbolAtLocation(component, expr);
    return type?.aliasTypeArguments?.[0] ?? (type && paramsTypeOf(type, expr));
  };

  const render = (type) => {
    if (!type) return 'undefined';
    const node = checker.typeToTypeNode(
      type,
      undefined,
      ts.NodeBuilderFlags.NoTruncation | ts.NodeBuilderFlags.UseFullyQualifiedType
    );
    return node ? printer.printNode(ts.EmitHint.Unspecified, node, blank) : 'undefined';
  };

  for (const file of program.getSourceFiles()) {
    if (file.isDeclarationFile || file.fileName.includes('node_modules')) continue;

    const visit = (node) => {
      if (ts.isJsxSelfClosingElement(node) || ts.isJsxOpeningElement(node)) {
        const tag = node.tagName.getText();
        if (TAGS.has(tag) && fromLibrary(node.tagName)) {
          const nameAttr = attribute(node, 'name');
          const where = `${path.relative(cwd, file.fileName)}:${
            file.getLineAndCharacterOfPosition(node.getStart()).line + 1
          }`;
          if (!nameAttr || !ts.isStringLiteral(nameAttr)) {
            warnings.push(`${where}: <${tag}> needs a literal name to be typed.`);
          } else if (routes.has(nameAttr.text)) {
            if (!MERGES.has(tag)) warnings.push(`${where}: duplicate route name "${nameAttr.text}".`);
          } else {
            const component = attribute(node, 'component');
            const loader = attribute(node, 'loader');
            const expr =
              !MERGES.has(tag) && component && ts.isJsxExpression(component)
                ? component.expression
                : undefined;
            const loaderExpr =
              !MERGES.has(tag) && loader && ts.isJsxExpression(loader) ? loader.expression : undefined;
            routes.set(
              nameAttr.text,
              expr ? render(paramsType(expr)) : loaderExpr ? render(loaderParamsType(loaderExpr)) : 'undefined'
            );
          }
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(file);
  }

  for (const warning of warnings) console.warn(`[navigation] ${warning}`);
  if (!routes.size) return undefined;

  const body = [...routes.keys()]
    .sort()
    .map((name) => `    ${name}: ${routes.get(name)};`)
    .join('\n');

  return {
    size: routes.size,
    text: `// Generated by app-navigation-codegen. Do not edit — rerun the script.
declare module 'app-navigation' {
  interface RouteParams {
${body}
  }
}

export {};
`,
  };
}

/** Writes only on a real change, so a watching tsc is not woken for nothing. */
function write(result) {
  if (!result) {
    console.error('[navigation] found no <Route>/<Tab>/<Stack>/<Modal> in this project.');
    return 1;
  }
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (current === result.text) {
    console.log(`${shown}: up to date (${result.size} routes)`);
    return 0;
  }
  if (check) {
    console.error(`[navigation] ${shown} is stale — rerun the codegen.`);
    return 1;
  }
  fs.writeFileSync(outPath, result.text);
  console.log(`${shown}: ${result.size} routes`);
  return 0;
}

const config = ts.getParsedCommandLineOfConfigFile(configPath, {}, {
  ...ts.sys,
  onUnRecoverableConfigFileDiagnostic: (d) => {
    console.error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    process.exit(1);
  },
});

if (!watch) {
  process.exit(write(collect(ts.createProgram(config.fileNames, config.options))));
}

// Watch mode keeps the program warm and rebuilds incrementally, so the second
// and later runs cost a fraction of the first.
const host = ts.createWatchCompilerHost(
  configPath,
  { noEmit: true },
  ts.sys,
  ts.createSemanticDiagnosticsBuilderProgram,
  () => {}, // the app's own tsc reports diagnostics; this only emits routes
  () => {}
);
const inner = host.afterProgramCreate;
host.afterProgramCreate = (builder) => {
  write(collect(builder.getProgram()));
  inner?.(builder);
};
ts.createWatchProgram(host);
console.log(`[navigation] watching for route changes -> ${shown}`);
